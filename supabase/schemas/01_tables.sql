-- Extensions
create extension if not exists "http" with schema "extensions";
create extension if not exists "citext" with schema "extensions";

-- Private schema (used by sales policies migration)
create schema if not exists "private";

create table public.companies (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    -- 'hotel' = direct customer directory, 'channel' = channel/partner directory.
    company_kind text not null default 'hotel',
    -- OTA / travel agency / meeting agency / corporate agreement / other (channels only).
    channel_type text,
    sector text,
    customer_category text,
    parent_company_id bigint,
    size smallint,
    linkedin_url text,
    website extensions.citext,
    phone_number text,
    address text,
    zipcode text,
    city text,
    state_abbr text,
    sales_id bigint,
    context_links json,
    country text,
    description text,
    revenue text,
    tax_identifier text,
    logo jsonb,
    hotel_type text,
    rooms smallint,
    opening_year smallint,
    hotel_services text[],
    average_room_rate numeric(12, 2)
);

create table public.contacts (
    id bigint generated by default as identity primary key,
    name text,
    first_name text,
    last_name text,
    gender text,
    title text,
    background text,
    avatar jsonb,
    first_seen timestamp with time zone,
    last_seen timestamp with time zone,
    has_newsletter boolean,
    status text,
    tags bigint[],
    company_id bigint,
    -- the contact who referred this contact (null = no referrer)
    referrer_contact_id bigint,
    sales_id bigint,
    wechat_id text,
    contact_type text,
    birthday date,
    communication_style text,
    attitude text,
    tenure_years numeric(5, 1),
    social_organization text,
    work_experience jsonb not null default '[]'::jsonb,
    education jsonb not null default '[]'::jsonb,
    email_jsonb jsonb,
    phone_jsonb jsonb
);

create table public.contact_notes (
    id bigint generated by default as identity (sequence name public."contactNotes_id_seq") not null,
    contact_id bigint not null,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    status text,
    attachments jsonb[]
);

create table public.deals (
    id bigint generated by default as identity primary key,
    name text not null,
    company_id bigint,
    stage text not null,
    status text not null default 'potential',
    deal_type text,
    -- 'direct' = direct hotel customer, 'channel' = sourced through a channel company.
    source_type text not null default 'direct',
    channel_id bigint,
    description text,
    decision_process text,
    budget bigint,
    final_amount bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    archived_at timestamp with time zone,
    expected_closing_date date,
    sales_id bigint,
    competitor_id bigint,
    attachments jsonb[],
    index smallint,
    -- True while nobody owns the deal: it sits in the public pool until claimed.
    is_unassigned boolean generated always as (sales_id is null) stored
);

-- Sandler-style opportunity people: every stakeholder of a deal with their role,
-- attitude, influence and personal pain (replaces the old deals.contact_ids array).
create table public.deal_contacts (
    id bigint generated by default as identity primary key,
    deal_id bigint not null,
    contact_id bigint not null,
    role text,
    attitude text,
    influence text,
    pain text,
    index smallint
);

create unique index uq__deal_contacts__deal_contact on public.deal_contacts using btree (deal_id, contact_id);

-- One row per pain identified during the diagnosis stage.
create table public.deal_pains (
    id bigint generated by default as identity primary key,
    deal_id bigint not null,
    symptom text,
    cause text,
    duration text,
    quantified_loss text,
    index smallint
);

-- One row per key event on the customer's decision timeline.
create table public.deal_milestones (
    id bigint generated by default as identity primary key,
    deal_id bigint not null,
    event text,
    date date,
    index smallint
);

-- One row per customer meeting / interaction, with attendees from both sides.
create table public.deal_meetings (
    id bigint generated by default as identity primary key,
    deal_id bigint not null,
    meeting_date date,
    customer_attendee_ids bigint[],
    our_attendee_ids bigint[],
    content text,
    next_steps text,
    created_at timestamp with time zone not null default now(),
    sales_id bigint
);

-- Known competitors (one of the four core entities of the model).
create table public.competitors (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    brand_influence text,
    market_price text,
    advantages text,
    weaknesses text,
    sales_id bigint
);

create table public.deal_notes (
    id bigint generated by default as identity (sequence name public."dealNotes_id_seq") not null,
    deal_id bigint not null,
    type text,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    attachments jsonb[]
);

create table public.sales (
    id bigint generated by default as identity primary key,
    name text,
    first_name text not null default 'Pending'::text,
    last_name text not null default 'Pending'::text,
    email extensions.citext not null,
    administrator boolean not null,
    user_id uuid not null,
    avatar jsonb,
    disabled boolean not null default false,
    secondary_emails jsonb not null default '[]'::jsonb,
    constraint sales_secondary_emails_is_array check (jsonb_typeof(secondary_emails) = 'array')
);

create unique index uq__sales__user_id on public.sales using btree (user_id);

create table public.tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null
);

create table public.tasks (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    type text,
    text text,
    due_date timestamp with time zone,
    done_date timestamp with time zone,
    sales_id bigint,
    created_at timestamp with time zone not null default now()
);

create table public.configuration (
    id integer not null default 1 primary key,
    config jsonb not null default '{}'::jsonb,
    constraint configuration_singleton check (id = 1)
);

create table public.favicons_excluded_domains (
    id bigint generated by default as identity primary key,
    domain text not null
);

create table public.user_invitations (
    user_id uuid primary key
);

