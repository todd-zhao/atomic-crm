create table public.assistant_threads (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id) on delete cascade,
    durable_conversation_id text not null,
    title text not null default 'New conversation',
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    last_message_at timestamp with time zone
);

create index assistant_threads_user_id_idx on public.assistant_threads using btree (user_id);

-- Provider configuration per user. The API key is AES-256-GCM encrypted by the
-- assistant service with ASSISTANT_ENCRYPTION_KEY; only service_role may read this table.
create table public.assistant_credentials (
    user_id uuid primary key references auth.users(id) on delete cascade,
    base_url text not null,
    model text not null,
    api_key_ciphertext text not null,
    api_key_hint text not null default '',
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);